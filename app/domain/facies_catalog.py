def facies_metadata(code: str) -> dict[str, str]:
    """Return a copy, so editing a layer never mutates the catalogue."""
    key = str(code or "").strip().casefold()
    return next((dict(item) for item in FACIES_CATALOG if item["Код фации"].casefold() == key), {})


def facies_title(item: dict[str, str]) -> str:
    return f"{item['Код фации']} · {item['Индекс фации']} · {item['Название фации']}"
